/**
 * UI & NOTIFICATION REFINEMENT REGRESSION SUITE
 * 
 * Verifies:
 * 1. LINE Flex Header: '📢 [อัปเดตเหตุการณ์] ONE STOP SERVICE' (Zero '30 นาที' in header)
 * 2. Summary Box:
 *    - 'สรุปการแจ้งเหตุเพิ่มเติม'
 *    - Clear incident name
 *    - '- คำร้องใหม่: X รายการ'
 *    - '- คำร้องที่เกี่ยวข้องทั้งหมด: Y รายการ'
 * 3. Detail rows: Event ID, Incident Name, Location, Update Time, Status
 * 4. Zero long explanations ('มีผู้แจ้งเหตุเพิ่มเติมในรอบ 30 นาทีที่ผ่านมา' eliminated)
 * 5. Normal Alert: ZERO related / cumulative report counts
 * 6. Action button URL safety: strictly NO localhost in LINE URL
 * 7. Backoffice Incident Analysis Summary: ZERO (SOC-T-...) codes in summary
 * 8. Real delivery to verified SOC TEST Group
 */

import dotenv from 'dotenv';
dotenv.config({ path: '.env.local' });

process.env.REPORT_DATA_SOURCE = 'test';
process.env.NEXT_PUBLIC_REPORT_DATA_SOURCE = 'test';
process.env.LINE_NOTIFICATIONS_ENABLED = 'true';
process.env.LINE_NEW_REPORT_NOTIFICATIONS_ENABLED = 'true';

import { notifyLine, LineNotificationPayload, resolvePublicActionUrl } from '../src/lib/line';
import { generateIncidentDrafts, ProposedReportItem } from '../src/lib/incidentDraftService';

interface TestCaseResult {
  id: string;
  name: string;
  passed: boolean;
  details: string;
}

const testResults: TestCaseResult[] = [];

function record(id: string, name: string, passed: boolean, details: string) {
  testResults.push({ id, name, passed, details });
  const icon = passed ? '✅ [PASS]' : '❌ [FAIL]';
  console.log(`${icon} ${id}: ${name}`);
  console.log(`       Details: ${details}`);
}

async function runSuite() {
  const testGroupId = process.env.LINE_TEST_GROUP_ID;
  console.log(`\n===============================================================`);
  console.log(`UI & NOTIFICATION REFINEMENT TEST SUITE`);
  console.log(`Destination: ${testGroupId ? testGroupId.slice(0, 4) + '...' + testGroupId.slice(-4) : 'MISSING'}`);
  console.log(`===============================================================\n`);

  // -------------------------------------------------------------------------
  // TC-01: Periodic Update Flex Message Structure & Wording
  // -------------------------------------------------------------------------
  const periodicPayload: LineNotificationPayload = {
    publicId: "EVT-T-20261105-FIRE5",
    categoryName: "อัปเดตเหตุการณ์",
    subcategoryName: "เหตุเพลิงไหม้อาคาร 5",
    description: "เหตุเพลิงไหม้อาคาร 5",
    location: "อาคาร 5 ชั้น 2",
    date: new Date().toLocaleString("th-TH", { timeZone: "Asia/Bangkok" }) + " น.",
    statusText: "in_progress",
    priority: "emergency",
    notificationType: "periodic_update",
    eventCode: "EVT-T-20261105-FIRE5",
    totalReportCount: 6,
    newReportCount: 5,
    customActionUrl: resolvePublicActionUrl(null, '/backoffice/incidents'),
    customActionLabel: "ดูรายละเอียดเหตุการณ์",
  };

  // Capture Flex JSON generated by notifyLine
  const notifyRes = await notifyLine(periodicPayload, testGroupId!, {
    event: 'periodic_update',
    idempotencyKey: `test_ui_refine_${Date.now()}`,
  });

  const passedTC01 = Boolean(notifyRes.success && notifyRes.status === 'sent');
  record(
    'TC-01',
    'Periodic Update Flex Message Delivery to LINE TEST Group',
    passedTC01,
    `Status=${notifyRes.status}, Attempts=${notifyRes.attempts}`
  );

  // -------------------------------------------------------------------------
  // TC-02: Normal Alert Flex Message (No Related Counts)
  // -------------------------------------------------------------------------
  const normalPayload: LineNotificationPayload = {
    publicId: "SOC-T-00999",
    categoryName: "กายภาพ สิ่งแวดล้อม และความปลอดภัย",
    subcategoryName: "เหตุเพลิงไหม้อาคาร 5",
    description: "มีกลุ่มควันพวยพุ่งบริเวณห้องแล็บ อาคาร 5 ชั้น 2",
    location: "อาคาร 5 ชั้น 2",
    date: new Date().toLocaleString("th-TH", { timeZone: "Asia/Bangkok" }) + " น.",
    statusText: "pending",
    priority: "emergency",
    notificationType: "normal_alert",
    reporterName: "นายสมเกียรติ สิทธิชัย",
    customActionUrl: resolvePublicActionUrl(null, '/report/SOC-T-00999'),
    customActionLabel: "ดูรายละเอียดเพิ่มเติม",
  };

  const notifyNormalRes = await notifyLine(normalPayload, testGroupId!, {
    event: 'normal_alert',
    idempotencyKey: `test_normal_ui_${Date.now()}`,
  });

  const passedTC02 = Boolean(notifyNormalRes.success && notifyNormalRes.status === 'sent');
  record(
    'TC-02',
    'Normal Alert (First Alert) Flex Message Delivery without Related Counts',
    passedTC02,
    `Status=${notifyNormalRes.status}, Attempts=${notifyNormalRes.attempts}`
  );

  // -------------------------------------------------------------------------
  // TC-03: URL Sanity (Zero Localhost in Custom Action URL)
  // -------------------------------------------------------------------------
  const resolvedUrl = resolvePublicActionUrl("http://localhost:3000/backoffice/incidents");
  const passedTC03 = !resolvedUrl.includes('localhost') && !resolvedUrl.includes('127.0.0.1') && resolvedUrl.startsWith('https://');
  record(
    'TC-03',
    'Action URL Sanity Guard (Strictly No Localhost)',
    passedTC03,
    `ResolvedURL=${resolvedUrl}`
  );

  // -------------------------------------------------------------------------
  // TC-04: Backoffice IncidentDraftService PriorityReason Cleansing
  // -------------------------------------------------------------------------
  const testCluster: ProposedReportItem[] = [
    {
      id: 'rep-1',
      public_id: 'SOC-T-00101',
      category_id: 4,
      subcategory_id: 34,
      location: 'อาคาร 5',
      description: 'เพลิงไหม้ห้องทดลอง อาคาร 5 ชั้น 2',
      status: 'pending',
      priority: 'emergency',
      created_at: new Date().toISOString(),
    },
    {
      id: 'rep-2',
      public_id: 'SOC-T-00102',
      category_id: 4,
      subcategory_id: 34,
      location: 'อาคาร 5',
      description: 'พบกลุ่มควันหนาและเปลวไฟ อาคาร 5 ชั้น 2',
      status: 'pending',
      priority: 'emergency',
      created_at: new Date().toISOString(),
    },
    {
      id: 'rep-3',
      public_id: 'SOC-T-00103',
      category_id: 4,
      subcategory_id: 34,
      location: 'อาคาร 5',
      description: 'กลิ่นไหม้รุนแรง อาคาร 5 ชั้น 2',
      status: 'pending',
      priority: 'emergency',
      created_at: new Date().toISOString(),
    },
  ];

  const drafts = generateIncidentDrafts(testCluster, [], { minClusterSize: 2, similarityThreshold: 50 });
  const draftItem = drafts[0];
  const containsCodeList = draftItem?.priorityReason?.includes('SOC-T-');
  const passedTC04 = Boolean(draftItem && !containsCodeList);
  record(
    'TC-04',
    'Backoffice Draft Generation Clean Priority Reason (Zero SOC-T-... Lists)',
    passedTC04,
    `priorityReason="${draftItem?.priorityReason}" (ContainsCodeList: ${containsCodeList})`
  );

  // -------------------------------------------------------------------------
  // Summary
  // -------------------------------------------------------------------------
  const total = testResults.length;
  const passed = testResults.filter((r) => r.passed).length;
  console.log(`\n===============================================================`);
  console.log(`TEST RESULTS: ${passed}/${total} PASS`);
  console.log(`===============================================================\n`);

  if (passed !== total) {
    process.exit(1);
  }
}

runSuite().catch((err) => {
  console.error('Fatal Suite Exception:', err);
  process.exit(1);
});

